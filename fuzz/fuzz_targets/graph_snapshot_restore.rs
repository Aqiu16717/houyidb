//! 目标 2：图快照恢复（文件信封 + payload 层）。
//! EN: Target 2: graph snapshot restore (file envelope + payload layers).
//!
//! 断言的不变量 / Invariants:
//! EN: Invariants:
//! - 信封层（`decode_graph_snapshot_file`）：magic / version / `payload_len` 的
//!   **checked 算术**（u64::MAX 级长度必须归为干净 `Err`，不得在 debug 下加法
//!   panic、release 下回绕成误报）/ trailing 字节 / CRC32 不符——全部 `Err`。
//! EN: - Envelope layer (`decode_graph_snapshot_file`): magic / version / **checked
//! EN:   arithmetic** for `payload_len` (u64::MAX-scale lengths must map to a clean
//! EN:   `Err`, never an addition panic in debug or a wraparound false positive in
//! EN:   release) / trailing bytes / CRC32 mismatch — all `Err`.
//! - payload 层（`restore_graph_snapshot`）：结构不符（dims/metric/layers/乘数）
//!   → `Err`；墓碑 trailer 的伪造 count 必须先对账再预分配（`count*8 > 剩余`
//!   → `Truncated`），**不得 OOM**；尾随字节 → `TrailingBytes`；空目标守卫。
//! EN: - Payload layer (`restore_graph_snapshot`): structure mismatch
//! EN:   (dims/metric/layers/multiplier) → `Err`; a forged tombstone trailer count
//! EN:   must be reconciled before preallocation (`count*8 > remaining` →
//! EN:   `Truncated`), **must not OOM**; trailing bytes → `TrailingBytes`; empty
//! EN:   target guard.
//! - 任意输入不得 panic。
//! EN: - No input may panic.
//!
//! 覆盖策略 / Coverage strategy: 信封 CRC 会挡住随机变异，故本目标额外用
//! `encode_graph_snapshot_file` 把任意 payload 以**正确 CRC** 重新封装，让 fuzzer
//! 的变异真正落在图结构 / 墓碑 trailer 上。
//! EN: Coverage strategy: the envelope CRC blocks random mutation, so this target
//! EN: additionally re-wraps arbitrary payloads with a **correct CRC** via
//! EN: `encode_graph_snapshot_file`, making mutations land on the graph structure /
//! EN: tombstone trailer.
//!
//! 结构感知 / Structure-aware: 前 8 字节解成 `checkpoint_lsn`，余下字节
//! `take_rest()` 作 payload——语料种子是「8 字节 LSN + 真实图快照 payload」，
//! 变异因此落在图结构语法上而非长度前缀上。信封层仍喂**整段原始字节**，语料另
//! 附一份真实信封文件（`cargo run --example seed_corpus` 生成），保住
//! magic/version/长度算术/trailing/CRC 面的独立变异预算。
//! EN: Structure-aware: the first 8 bytes decode as `checkpoint_lsn`, and the rest
//! EN: becomes the payload via `take_rest()`; seeds are "8-byte LSN + real graph
//! EN: snapshot payload", so mutations land on the graph structure syntax rather
//! EN: than the length prefix. The envelope layer still receives the **entire raw
//! EN: byte string**, and the corpus includes a real envelope file (generated by
//! EN: `cargo run --example seed_corpus`), preserving an independent mutation
//! EN: budget for the magic/version/length-arithmetic/trailing/CRC surface.

use arbitrary::Unstructured;
use libfuzzer_sys::fuzz_target;
use std::sync::OnceLock;
use tokio::runtime::Runtime;

/// 与语料种子一致的维度：fuzzer 需要「猜中」结构期望才能深入，给小维度降低难度。
/// EN: Dimensions matching the corpus seed: the fuzzer must "guess" the structure
/// EN: expectation to go deeper, so small dimensions lower the difficulty.
const DIMS: usize = 4;

fn runtime() -> &'static Runtime {
    static RT: OnceLock<Runtime> = OnceLock::new();
    RT.get_or_init(|| {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .expect("fuzz runtime")
    })
}

fuzz_target!(|data: &[u8]| {
    use houyi_persistence::graph_snapshot_file::{
        decode_graph_snapshot_file, encode_graph_snapshot_file,
    };

    let mut u = Unstructured::new(data);
    let checkpoint_lsn = u.arbitrary::<u64>().unwrap_or(0);
    let payload = u.take_rest().to_vec();

    // ── 1) 信封层：任意原始字节 ─────────────────────────────────
    // EN: -- 1) Envelope layer: arbitrary raw bytes --
    let _ = decode_graph_snapshot_file(data);

    // ── 2) 自封装往返（不变量：自己编码的信封必须永远能解回同一 payload）──
    // EN: -- 2) Self-wrap round trip (invariant: a self-encoded envelope must always
    // EN: decode back to the same payload) --
    let envelope = encode_graph_snapshot_file(checkpoint_lsn, &payload);
    let decoded =
        decode_graph_snapshot_file(&envelope).expect("self-encoded envelope must always validate");
    assert_eq!(decoded.checkpoint_lsn, checkpoint_lsn);
    assert_eq!(decoded.payload, payload);

    // ── 3) payload 层：真实索引恢复（含墓碑 count OOM 守卫）──────
    // 每次新建索引：恢复是「空目标」操作，复用会让第二次起恒为 InvalidStructure。
    // EN: -- 3) Payload layer: real index restore (including the tombstone count OOM guard) --
    // EN: A fresh index per iteration: restore is an "empty target" operation; reusing one
    // EN: makes every run after the second InvalidStructure.
    let index = houyi_vector::HotBufferIndex::new(DIMS);
    let _ = runtime().block_on(index.restore_graph_snapshot(&payload));
});
